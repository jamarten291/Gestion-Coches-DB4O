    private boolean validInput() {
        boolean flag = true;
        
        JTextField[] tfList = { tfDni, tfNombre, tfEdad, tfEmail };
        
        for (JTextField jTextField : tfList) {
            if (jTextField.getText().isEmpty()) flag = false;
        }
        
        if (!HelperClass.tryParseToInt(tfEdad.getText())) {
            flag = false;
        }
        
        return flag;
    }
    
